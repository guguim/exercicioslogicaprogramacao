package exercicios4;

public class Exercicio01 {
    public static void main(String[] args) {
        //Elaborar um programa que apresente os quadrado dos números inteiros existentes na faixa de valores
        //de 15 até 200.

        for (int i = 15; i <= 200; i++) {
            int quadrado = i * 2;
            System.out.println("Quadrado do número " + i + " é " + quadrado);

        }
    }
}
